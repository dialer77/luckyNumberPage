/** 연말정산 신고 근로자 수 */
export const TOTAL_WORKERS = BUCKETS.reduce((s, b) => s + b[1], 0);
/** 1인 평균 총급여(원) */
export const AVERAGE_SALARY = Math.round(
  (BUCKETS.reduce((s, b) => s + b[2], 0) * 1e8) / TOTAL_WORKERS
);

// [가운데 백분위(상위 %), 그 구간 1인 평균 총급여(원)] — 상위 %가 커질수록 연봉은 작아짐
const POINTS: [number, number][] = (() => {
  const pts: [number, number][] = [];
  let prev = 0;
  for (const [end, people, payEok] of BUCKETS) {
    pts.push([(prev + end) / 2, (payEok * 1e8) / people]);
    prev = end;
  }
  return pts;
})();

const TOP = POINTS[0];
const BOTTOM = POINTS[POINTS.length - 1];

/** 연봉(총급여, 원) → 상위 % (0~100). 가장 높은 구간 평균보다 많으면 그 구간의 가운데 값. */
export function salaryTopPercent(salary: number): number {
  if (salary >= TOP[1]) return TOP[0];
  if (salary <= BOTTOM[1]) return 100;
  for (let i = 0; i < POINTS.length - 1; i++) {
    const [p0, s0] = POINTS[i];
    const [p1, s1] = POINTS[i + 1];
    if (salary <= s0 && salary >= s1) {
      const t = (s0 - salary) / (s0 - s1);
      return p0 + (p1 - p0) * t;
    }
  }
  return 100;
}

/** 상위 p% 경계에 해당하는 연봉(원) — salaryTopPercent의 역함수 */
export function salaryAtTopPercent(p: number): number {
  if (p <= TOP[0]) return Math.round(TOP[1]);
  if (p >= BOTTOM[0]) return Math.round(BOTTOM[1]);
  for (let i = 0; i < POINTS.length - 1; i++) {
    const [p0, s0] = POINTS[i];
    const [p1, s1] = POINTS[i + 1];
    if (p >= p0 && p <= p1) {
      const t = (p - p0) / (p1 - p0);
      return Math.round(s0 + (s1 - s0) * t);
    }
  }
  return Math.round(BOTTOM[1]);
}

/** 중위 총급여(원) — 상위 50% 경계 */
export const MEDIAN_SALARY = salaryAtTopPercent(50);
